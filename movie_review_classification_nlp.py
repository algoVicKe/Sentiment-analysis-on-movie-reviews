"""Model Building - LSTM Model

Build an LSTM-based model for sentiment classification.
"""

# Step 1: LSTM Model
print("Building LSTM Model...")

def build_lstm_model(vocab_size, embedding_dim, max_length):
    """
    Build an LSTM-based sentiment classification model.

    Architecture:
    - Embedding layer: Learns word embeddings from scratch
    - LSTM layer: Captures sequential dependencies
    - Dropout layer: Prevents overfitting
    - Dense layer: Outputs binary classification
    """
    model = Sequential([
        Embedding(vocab_size, embedding_dim, input_length=max_length),
        LSTM(128, dropout=0.2, recurrent_dropout=0.2),
        Dense(64, activation='relu'),
        Dropout(0.5),
        Dense(1, activation='sigmoid')
    ])

    model.compile(
        optimizer='adam',
        loss='binary_crossentropy',
        metrics=['accuracy']
    )

    return model

