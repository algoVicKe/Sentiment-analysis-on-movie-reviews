def build_cnn_model(vocab_size, embedding_dim, max_length):
    """
    Build a CNN-based sentiment classification model.

    Architecture:
    - Embedding layer: Learns word embeddings from scratch
    - Conv1D layer: Extracts local features (n-gram patterns)
    - MaxPooling1D layer: Reduces dimensionality
    - GlobalMaxPooling1D layer: Aggregates features
    - Dense layers: Classification
    """
    model = Sequential([
        Embedding(vocab_size, embedding_dim, input_length=max_length),
        Conv1D(128, 5, activation='relu'),
        MaxPooling1D(5),
        Conv1D(128, 5, activation='relu'),
        GlobalMaxPooling1D(),
        Dense(128, activation='relu'),
        Dropout(0.5),
        Dense(1, activation='sigmoid')
    ])

    model.compile(
        optimizer='adam',
        loss='binary_crossentropy',
        metrics=['accuracy']
    )

    return model

