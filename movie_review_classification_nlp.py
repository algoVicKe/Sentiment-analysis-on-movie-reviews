# Step 3: LSTM with Attention Model
print("Building LSTM with Attention Model...")

def build_attention_model(vocab_size, embedding_dim, max_length):
    """
    Build an LSTM-based model with attention mechanism.

    Architecture:
    - Embedding layer: Learns word embeddings
    - Bidirectional LSTM: Captures context from both directions
    - Attention layer: Focuses on important words
    - Dense layers: Classification
    """
    # Input layer
    inputs = Input(shape=(max_length,))

    # Embedding layer
    embedding = Embedding(vocab_size, embedding_dim)(inputs)

    # Bidirectional LSTM
    lstm_out = Bidirectional(LSTM(64, return_sequences=True))(embedding)

    # Attention mechanism (using Keras attention layer)
    attention = Attention()([lstm_out, lstm_out])

    # Global average pooling
    pooled = tf.keras.layers.GlobalAveragePooling1D()(attention)

    # Dense layers
    dense1 = Dense(64, activation='relu')(pooled)
    dropout = Dropout(0.5)(dense1)
    outputs = Dense(1, activation='sigmoid')(dropout)

    model = Model(inputs=inputs, outputs=outputs)

    model.compile(
        optimizer='adam',
        loss='binary_crossentropy',
        metrics=['accuracy']
    )

    return model

# Build and compile the attention model
